#include "compositors/niri/niri_phone_cast.h"

#include "compositors/niri/niri_config_files.h"

#include <format>
#include <system_error>

namespace compositors::niri {

  std::filesystem::path phoneCastIncludePath() { return includePath(kPhoneCastIncludeFileName); }

  std::string kdlForPhoneCast() {
    // The iPhone mirror is the shell's own toplevel (app-id helix-phone). scrcpy is
    // still an external window; uxplay stays matched for anyone running it by hand
    // (its GL sink titles the window "OpenGL Renderer", so a title match never applied).
    return std::format(
        R"(// Generated by Helix for Phone → Cast mirror windows. Edits here are overwritten.
window-rule {{
    match app-id="^{}$"
    match app-id="^uxplay$"
    match app-id="^scrcpy$"
    match title="Helix Phone$"
    open-floating true
    default-column-width {{ fixed {}; }}
    default-window-height {{ fixed {}; }}
    min-width 280
    max-width 520
    min-height 560
    max-height 1100
    geometry-corner-radius {}
    clip-to-geometry true
    border {{ off; }}
    focus-ring {{ off; }}
    shadow {{
        on
        softness 40
        spread 6
        offset x=0 y=12
        color "#00000099"
    }}
}}
)",
        kPhoneMirrorAppId, kPhoneMirrorWidth, kPhoneMirrorHeight, kPhoneMirrorCornerRadius
    );
  }

  InstallResult ensurePhoneCastWindowRules() { return ensurePhoneCastWindowRulesInto(configPath()); }

  InstallResult ensurePhoneCastWindowRulesInto(const std::filesystem::path& configFile) {
    InstallResult result;
    if (configFile.empty()) {
      result.error = "niri config path is unknown";
      return result;
    }
    std::error_code ec;
    if (!std::filesystem::exists(configFile, ec) || ec) {
      result.error = "niri config not found";
      return result;
    }
    const auto include = configFile.parent_path() / std::string(kPhoneCastIncludeFileName);
    if (!writeFile(include, kdlForPhoneCast(), result.error)) {
      return result;
    }
    if (!appendInclude(configFile, kPhoneCastIncludeFileName, result.error)) {
      return result;
    }
    result.ok = true;
    result.added = 1;
    return result;
  }

} // namespace compositors::niri
