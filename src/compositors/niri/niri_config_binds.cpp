    constexpr std::string_view kManagedHeader =
        "// Generated by Noctalia from Settings → Keybinds. Extra binds in this file are kept.\n";

    [[nodiscard]] bool isBindsInclude(std::string_view path) {
      return fileNameOf(path) == kBindsIncludeFileName;
    }

    [[nodiscard]] std::string normalizeIpc(std::string command) {
      command = StringUtils::trim(command);
      while (!command.empty() && (command.back() == ';' || command.back() == '&')) {
        command.pop_back();
        command = StringUtils::trim(command);
      }
      constexpr std::string_view kPrefix = "noctalia msg ";
      if (command.starts_with(kPrefix)) {
        command = StringUtils::trim(command.substr(kPrefix.size()));
      }
      std::string collapsed;
      collapsed.reserve(command.size());
      bool space = false;
      for (const char c : command) {
        if (std::isspace(static_cast<unsigned char>(c)) != 0) {
          space = true;
          continue;
        }
        if (space && !collapsed.empty()) {
          collapsed.push_back(' ');
        }
        space = false;
        collapsed.push_back(c);
      }
      return collapsed;
    }

    [[nodiscard]] std::string ipcFromSpawnArgv(const std::vector<std::string>& args) {
      if (args.size() < 3) {
        return {};
      }
      const std::string binary = fileNameOf(args[0]);
      if (binary != "noctalia" || args[1] != "msg") {
        return {};
      }
      std::string command;
      for (std::size_t i = 2; i < args.size(); ++i) {
        if (!command.empty()) {
          command.push_back(' ');
        }
        command += args[i];
      }
      return normalizeIpc(command);
    }

    void collectBindsFromBlock(std::string_view block, std::vector<ParsedBind>& out) {
      std::size_t i = 0;
      while (i < block.size()) {
        while (i < block.size() && std::isspace(static_cast<unsigned char>(block[i])) != 0) {
          ++i;
        }
        if (i >= block.size()) {
          break;
        }
        const std::size_t keyStart = i;
        while (i < block.size() && isIdent(block[i])) {
          ++i;
        }
        if (i == keyStart) {
          ++i;
          continue;
        }
        std::string key(block.substr(keyStart, i - keyStart));
        const std::size_t brace = block.find('{', i);
        if (brace == std::string_view::npos) {
          break;
        }
        int depth = 0;
        bool inString = false;
        bool escape = false;
        std::size_t end = brace;
        for (; end < block.size(); ++end) {
          const char c = block[end];
          if (inString) {
            if (escape) {
              escape = false;
              continue;
            }
            if (c == '\\') {
              escape = true;
              continue;
            }
            if (c == '"') {
              inString = false;
            }
            continue;
          }
          if (c == '"') {
            inString = true;
            continue;
          }
          if (c == '{') {
            ++depth;
          } else if (c == '}') {
            --depth;
            if (depth == 0) {
              break;
            }
          }
        }
        if (end >= block.size() || depth != 0) {
          break;
        }
        const auto action = block.substr(brace + 1, end - brace - 1);
        ParsedBind bind;
        bind.key = std::move(key);
        bind.action = StringUtils::trim(action);
        if (const auto ipc = ipcCommandFromAction(action); ipc.has_value()) {
          bind.ipcCommand = *ipc;
        }
        out.push_back(std::move(bind));
        i = end + 1;
      }
    }

    void collectBinds(std::string_view kdl, std::vector<ParsedBind>& out) {
      const std::string stripped = stripComments(kdl);
      std::size_t search = 0;
      while (search < stripped.size()) {
        const auto found = stripped.find("binds", search);
        if (found == std::string::npos) {
          break;
        }
        if (found > 0 && isIdent(stripped[found - 1])) {
          search = found + 5;
          continue;
        }
        if (found + 5 < stripped.size() && isIdent(stripped[found + 5])) {
          search = found + 5;
          continue;
        }
        std::size_t i = found + 5;
        while (i < stripped.size() && std::isspace(static_cast<unsigned char>(stripped[i])) != 0) {
          ++i;
        }
        if (i >= stripped.size() || stripped[i] != '{') {
          search = found + 5;
          continue;
        }
        int depth = 0;
        bool inString = false;
        bool escape = false;
        std::size_t end = i;
        for (; end < stripped.size(); ++end) {
          const char c = stripped[end];
          if (inString) {
            if (escape) {
              escape = false;
              continue;
            }
            if (c == '\\') {
              escape = true;
              continue;
            }
            if (c == '"') {
              inString = false;
            }
            continue;
          }
          if (c == '"') {
            inString = true;
            continue;
          }
          if (c == '{') {
            ++depth;
          } else if (c == '}') {
            --depth;
            if (depth == 0) {
              break;
            }
          }
        }
        if (end < stripped.size() && depth == 0) {
          collectBindsFromBlock(std::string_view(stripped).substr(i + 1, end - i - 1), out);
          search = end + 1;
        } else {
          break;
        }
      }
    }

    void scanRecursive(
        const std::filesystem::path& path, ConfigScan& scan, std::unordered_set<std::string>& visited, int depth
    ) {
      if (depth > 16 || path.empty()) {
        return;
      }
      std::error_code ec;
      const auto canonical = std::filesystem::weakly_canonical(path, ec);
      const std::string key = (!ec ? canonical : path).string();
      if (!visited.insert(key).second) {
        return;
      }
      const std::string text = readFile(path);
      if (text.empty() && !std::filesystem::exists(path, ec)) {
        return;
      }
      collectBinds(text, scan.binds);
      for (const auto& include : parseIncludes(text, path)) {
        if (isBindsInclude(include.string())) {
          scan.hasBindsInclude = true;
        }
        scanRecursive(include, scan, visited, depth + 1);
      }
    }

    [[nodiscard]] std::string writeOwnedBinds(const std::vector<ParsedBind>& managedBinds) {
      std::string body = std::string(kManagedHeader);
      body += "binds {\n";
      for (const auto& bind : managedBinds) {
        body += "    ";
        body += bind.key;
        body += " { ";
        if (!bind.ipcCommand.empty()) {
          body += "spawn-sh \"noctalia msg ";
          body += bind.ipcCommand;
          body += "\";";
        } else if (!bind.action.empty()) {
          body += bind.action;
          if (bind.action.back() != ';') {
            body += ';';
          }
        }
        body += " }\n";
      }
      body += "}\n";
      return body;
    }

    [[nodiscard]] const RecommendedBind* findRecommended(std::string_view id) {
      for (const auto& bind : kRecommended) {
        if (bind.id == id) {
          return &bind;
        }
      }
      return nullptr;
    }

    [[nodiscard]] std::string niriKeysymName(std::uint32_t sym) {
      if (sym == 0) {
        return {};
      }
      std::array<char, 64> buf{};
      const int n = xkb_keysym_get_name(static_cast<xkb_keysym_t>(sym), buf.data(), buf.size());
      if (n <= 0) {
        return {};
      }
      std::string name(buf.data(), static_cast<std::size_t>(n));
      if (name == "space") {
        return "Space";
      }
      if (name == "comma") {
        return "Comma";
      }
      if (name == "period") {
        return "Period";
      }
      if (name == "slash") {
        return "Slash";
      }
      if (name == "minus") {
        return "Minus";
      }
      if (name == "equal") {
        return "Equal";
      }
      if (name.size() == 1 && name[0] >= 'a' && name[0] <= 'z') {
        name[0] = static_cast<char>(name[0] - ('a' - 'A'));
      }
      return name;
    }

