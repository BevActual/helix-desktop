  std::string kdlLine(const RecommendedBind& bind) {
    return std::string(bind.key) + " { spawn-sh \"noctalia msg " + std::string(bind.ipcCommand) + "\"; }";
  }

  std::string kdlBlock(const std::vector<RecommendedBind>& binds) {
    std::string out = "binds {\n";
    for (const auto& bind : binds) {
      out += "    ";
      out += kdlLine(bind);
      out += '\n';
    }
    out += "}\n";
    return out;
  }

  std::optional<std::string> ipcCommandFromAction(std::string_view action) {
    const std::string stripped = stripComments(action);
    std::size_t spawnSh = stripped.find("spawn-sh");
    if (spawnSh != std::string::npos
        && (spawnSh == 0 || !isIdent(stripped[spawnSh - 1]))
        && (spawnSh + 8 >= stripped.size() || !isIdent(stripped[spawnSh + 8]))) {
      std::size_t i = spawnSh + 8;
      if (const auto quoted = parseQuoted(stripped, i); quoted.has_value()) {
        if (quoted->find("noctalia msg") != std::string::npos) {
          const std::string ipc = normalizeIpc(*quoted);
          if (!ipc.empty()) {
            return ipc;
          }
        }
      }
    }

    std::size_t spawn = 0;
    while ((spawn = stripped.find("spawn", spawn)) != std::string::npos) {
      if ((spawn == 0 || !isIdent(stripped[spawn - 1]))
          && (spawn + 5 >= stripped.size() || !isIdent(stripped[spawn + 5]))) {
        std::size_t i = spawn + 5;
        std::vector<std::string> args;
        while (true) {
          const auto quoted = parseQuoted(stripped, i);
          if (!quoted.has_value()) {
            break;
          }
          args.push_back(*quoted);
        }
        if (const auto ipc = ipcFromSpawnArgv(args); !ipc.empty()) {
          return ipc;
        }
      }
      spawn += 5;
    }
    return std::nullopt;
  }

  std::vector<ParsedBind> parseBinds(std::string_view kdl) {
    std::vector<ParsedBind> binds;
    collectBinds(kdl, binds);
    return binds;
  }

  std::string niriKeyFromChord(const KeyChord& chord) {
    const std::string key = niriKeysymName(chord.sym);
    if (key.empty()) {
      return {};
    }
    std::string out;
    if ((chord.modifiers & KeyMod::Super) != 0) {
      out += "Mod+";
    }
    if ((chord.modifiers & KeyMod::Ctrl) != 0) {
      out += "Ctrl+";
    }
    if ((chord.modifiers & KeyMod::Alt) != 0) {
      out += "Alt+";
    }
    if ((chord.modifiers & KeyMod::Shift) != 0) {
      out += "Shift+";
    }
    out += key;
    return out;
  }

  std::optional<KeyChord> niriKeyToChord(std::string_view key) {
    const std::string spec = StringUtils::trim(key);
    if (spec.empty()) {
      return std::nullopt;
    }

    std::vector<std::string> tokens;
    std::size_t start = 0;
    while (start <= spec.size()) {
      const auto plus = spec.find('+', start);
      const std::size_t len = (plus == std::string::npos) ? (spec.size() - start) : (plus - start);
      const std::string token = StringUtils::trim(std::string_view(spec).substr(start, len));
      if (token.empty()) {
        return std::nullopt;
      }
      tokens.push_back(token);
      if (plus == std::string::npos) {
        break;
      }
      start = plus + 1;
    }
    if (tokens.empty()) {
      return std::nullopt;
    }

    std::uint32_t modifiers = 0;
    for (std::size_t i = 0; i + 1 < tokens.size(); ++i) {
      const std::string mod = StringUtils::toLower(tokens[i]);
      if (mod == "mod" || mod == "super" || mod == "super_l" || mod == "super_r" || mod == "meta" || mod == "win") {
        modifiers |= KeyMod::Super;
      } else if (mod == "ctrl" || mod == "control" || mod == "ctl") {
        modifiers |= KeyMod::Ctrl;
      } else if (mod == "alt" || mod == "option") {
        modifiers |= KeyMod::Alt;
      } else if (mod == "shift") {
        modifiers |= KeyMod::Shift;
      } else {
        return std::nullopt;
      }
    }

    std::string keyName = tokens.back();
    if (StringUtils::toLower(keyName) == "space") {
      keyName = "space";
    } else if (StringUtils::toLower(keyName) == "comma") {
      keyName = "comma";
    }
    const xkb_keysym_t sym = xkb_keysym_from_name(keyName.c_str(), XKB_KEYSYM_CASE_INSENSITIVE);
    if (sym == XKB_KEY_NoSymbol) {
      return std::nullopt;
    }
    return KeyChord{.sym = static_cast<std::uint32_t>(sym), .modifiers = modifiers};
  }

  ConfigScan scanConfig() { return scanConfigFile(configPath()); }

  ConfigScan scanConfigFile(const std::filesystem::path& path) {
    ConfigScan scan;
    scan.configPath = path;
    scan.bindsIncludePath = path.parent_path() / std::string(kBindsIncludeFileName);
    std::error_code ec;
    scan.configExists = std::filesystem::exists(path, ec) && !ec;
    std::unordered_set<std::string> visited;
    if (scan.configExists) {
      scanRecursive(path, scan, visited, 0);
    }
    if (!scan.hasBindsInclude) {
      scanRecursive(scan.bindsIncludePath, scan, visited, 0);
    }
    return scan;
  }

  std::vector<BindStatus> bindStatuses(const ConfigScan& scan) {
    const auto ownedBinds = parseBinds(readFile(scan.bindsIncludePath));
    std::vector<BindStatus> statuses;
    statuses.reserve(recommendedBinds().size());
    for (const auto& recommended : recommendedBinds()) {
      BindStatus status{.recommended = recommended};
      bool keyUsedByOther = false;
      for (const auto& bind : scan.binds) {
        if (bind.ipcCommand == recommended.ipcCommand) {
          status.boundKeys.push_back(bind.key);
        } else if (bind.key == recommended.key) {
          keyUsedByOther = true;
        }
      }
      for (const auto& bind : ownedBinds) {
        if (bind.ipcCommand == recommended.ipcCommand) {
          status.inOwnedInclude = true;
          break;
        }
      }
      status.keyConflict = status.boundKeys.empty() && keyUsedByOther;
      statuses.push_back(std::move(status));
    }
    return statuses;
  }

  std::vector<RecommendedBind> missingRecommended(const ConfigScan& scan) {
    std::vector<RecommendedBind> missing;
    for (const auto& status : bindStatuses(scan)) {
      if (status.boundKeys.empty() && !status.keyConflict) {
        missing.push_back(status.recommended);
      }
    }
    return missing;
  }

  InstallResult installMissing() { return installMissingInto(configPath()); }

  InstallResult installMissingInto(const std::filesystem::path& configFile) {
    InstallResult result;
    if (configFile.empty()) {
      result.error = "niri config path is unknown";
      return result;
    }
    auto scan = scanConfigFile(configFile);
    if (!scan.configExists) {
      result.error = "niri config not found";
      return result;
    }

    const auto missing = missingRecommended(scan);
    int skipped = 0;
    for (const auto& status : bindStatuses(scan)) {
      if (status.keyConflict) {
        ++skipped;
      }
    }
    result.skippedConflicts = skipped;

    std::vector<ParsedBind> managedBinds = parseBinds(readFile(scan.bindsIncludePath));
    std::unordered_set<std::string> managedKeys;
    for (const auto& bind : managedBinds) {
      managedKeys.insert(bind.key);
    }
    for (const auto& bind : missing) {
      if (managedKeys.contains(std::string(bind.key))) {
        continue;
      }
      managedBinds.push_back(
          {.key = std::string(bind.key),
           .ipcCommand = std::string(bind.ipcCommand),
           .action = "spawn-sh \"noctalia msg " + std::string(bind.ipcCommand) + "\";"}
      );
      managedKeys.insert(std::string(bind.key));
      ++result.added;
    }

    if (!writeFile(scan.bindsIncludePath, writeOwnedBinds(managedBinds), result.error)) {
      return result;
    }
    if (!appendInclude(configFile, kBindsIncludeFileName, result.error)) {
      return result;
    }
    result.ok = true;
    return result;
  }

  InstallResult setRecommendedKey(std::string_view id, std::string_view niriKey) {
    return setRecommendedKeyInto(configPath(), id, niriKey);
  }

  InstallResult setRecommendedKeyInto(
      const std::filesystem::path& configFile, std::string_view id, std::string_view niriKey
  ) {
    InstallResult result;
    const auto* recommended = findRecommended(id);
    if (recommended == nullptr) {
      result.error = "unknown niri bind";
      return result;
    }
    const std::string key = StringUtils::trim(niriKey);
    if (key.empty()) {
      result.error = "empty key";
      return result;
    }
    if (configFile.empty()) {
      result.error = "niri config path is unknown";
      return result;
    }
    auto scan = scanConfigFile(configFile);
    if (!scan.configExists) {
      result.error = "niri config not found";
      return result;
    }

    for (const auto& bind : scan.binds) {
      if (bind.key == key && bind.ipcCommand != recommended->ipcCommand) {
        result.error = "key is already used by another niri bind";
        result.skippedConflicts = 1;
        return result;
      }
    }

    std::vector<ParsedBind> managedBinds = parseBinds(readFile(scan.bindsIncludePath));
    bool replaced = false;
    for (auto& bind : managedBinds) {
      if (bind.ipcCommand == recommended->ipcCommand) {
        bind.key = key;
        replaced = true;
        break;
      }
    }
    if (!replaced) {
      managedBinds.push_back(
          {.key = key,
           .ipcCommand = std::string(recommended->ipcCommand),
           .action = "spawn-sh \"noctalia msg " + std::string(recommended->ipcCommand) + "\";"}
      );
    }
    result.added = replaced ? 0 : 1;

    if (!writeFile(scan.bindsIncludePath, writeOwnedBinds(managedBinds), result.error)) {
      return result;
    }
    if (!appendInclude(configFile, kBindsIncludeFileName, result.error)) {
      return result;
    }
    result.ok = true;
    return result;
  }

