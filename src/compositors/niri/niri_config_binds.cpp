    constexpr std::string_view kManagedHeader =
        "// Generated by Noctalia from Settings → Keybinds. Extra binds in this file are kept.\n";

    [[nodiscard]] std::filesystem::path xdgConfigHome() {
      if (const char* env = std::getenv("XDG_CONFIG_HOME"); env != nullptr && env[0] != '\0') {
        return std::filesystem::path(env);
      }
      if (const char* home = std::getenv("HOME"); home != nullptr && home[0] != '\0') {
        return std::filesystem::path(home) / ".config";
      }
      return {};
    }

    [[nodiscard]] std::string readFile(const std::filesystem::path& path) {
      std::ifstream in(path);
      if (!in) {
        return {};
      }
      std::ostringstream out;
      out << in.rdbuf();
      return out.str();
    }

    [[nodiscard]] bool writeFile(const std::filesystem::path& path, std::string_view contents, std::string& error) {
      std::error_code ec;
      const auto parent = path.parent_path();
      if (!parent.empty()) {
        std::filesystem::create_directories(parent, ec);
        if (ec) {
          error = "failed to create " + parent.string();
          return false;
        }
      }
      std::ofstream out(path, std::ios::trunc);
      if (!out) {
        error = "failed to write " + path.string();
        return false;
      }
      out << contents;
      if (!out) {
        error = "failed to write " + path.string();
        return false;
      }
      return true;
    }

    [[nodiscard]] bool isIdent(char c) noexcept {
      return std::isalnum(static_cast<unsigned char>(c)) != 0 || c == '_' || c == '-' || c == '+';
    }

    [[nodiscard]] std::string stripComments(std::string_view in) {
      std::string out;
      out.reserve(in.size());
      bool inString = false;
      bool escape = false;
      for (std::size_t i = 0; i < in.size(); ++i) {
        const char c = in[i];
        if (inString) {
          out.push_back(c);
          if (escape) {
            escape = false;
            continue;
          }
          if (c == '\\') {
            escape = true;
            continue;
          }
          if (c == '"') {
            inString = false;
          }
          continue;
        }
        if (c == '"') {
          inString = true;
          out.push_back(c);
          continue;
        }
        if (c == '/' && i + 1 < in.size() && in[i + 1] == '/') {
          while (i < in.size() && in[i] != '\n') {
            ++i;
          }
          if (i < in.size()) {
            out.push_back('\n');
          }
          continue;
        }
        out.push_back(c);
      }
      return out;
    }

    [[nodiscard]] std::optional<std::string> parseQuoted(std::string_view text, std::size_t& i) {
      while (i < text.size() && std::isspace(static_cast<unsigned char>(text[i])) != 0) {
        ++i;
      }
      if (i >= text.size() || text[i] != '"') {
        return std::nullopt;
      }
      ++i;
      std::string value;
      bool escape = false;
      for (; i < text.size(); ++i) {
        const char c = text[i];
        if (escape) {
          value.push_back(c);
          escape = false;
          continue;
        }
        if (c == '\\') {
          escape = true;
          continue;
        }
        if (c == '"') {
          ++i;
          return value;
        }
        value.push_back(c);
      }
      return std::nullopt;
    }

    [[nodiscard]] std::string basenameOf(std::string_view path) {
      const auto slash = path.find_last_of("/\\");
      if (slash == std::string_view::npos) {
        return std::string(path);
      }
      return std::string(path.substr(slash + 1));
    }

    [[nodiscard]] bool isBindsInclude(std::string_view path) {
      return basenameOf(path) == kBindsIncludeFileName;
    }

    [[nodiscard]] std::string normalizeIpc(std::string command) {
      command = StringUtils::trim(command);
      while (!command.empty() && (command.back() == ';' || command.back() == '&')) {
        command.pop_back();
        command = StringUtils::trim(command);
      }
      constexpr std::string_view kPrefix = "noctalia msg ";
      if (command.starts_with(kPrefix)) {
        command = StringUtils::trim(command.substr(kPrefix.size()));
      }
      std::string collapsed;
      collapsed.reserve(command.size());
      bool space = false;
      for (const char c : command) {
        if (std::isspace(static_cast<unsigned char>(c)) != 0) {
          space = true;
          continue;
        }
        if (space && !collapsed.empty()) {
          collapsed.push_back(' ');
        }
        space = false;
        collapsed.push_back(c);
      }
      return collapsed;
    }

    [[nodiscard]] std::string ipcFromSpawnArgv(const std::vector<std::string>& args) {
      if (args.size() < 3) {
        return {};
      }
      const std::string binary = basenameOf(args[0]);
      if (binary != "noctalia" || args[1] != "msg") {
        return {};
      }
      std::string command;
      for (std::size_t i = 2; i < args.size(); ++i) {
        if (!command.empty()) {
          command.push_back(' ');
        }
        command += args[i];
      }
      return normalizeIpc(command);
    }

    void collectBindsFromBlock(std::string_view block, std::vector<ParsedBind>& out) {
      std::size_t i = 0;
      while (i < block.size()) {
        while (i < block.size() && std::isspace(static_cast<unsigned char>(block[i])) != 0) {
          ++i;
        }
        if (i >= block.size()) {
          break;
        }
        const std::size_t keyStart = i;
        while (i < block.size() && isIdent(block[i])) {
          ++i;
        }
        if (i == keyStart) {
          ++i;
          continue;
        }
        std::string key(block.substr(keyStart, i - keyStart));
        const std::size_t brace = block.find('{', i);
        if (brace == std::string_view::npos) {
          break;
        }
        int depth = 0;
        bool inString = false;
        bool escape = false;
        std::size_t end = brace;
        for (; end < block.size(); ++end) {
          const char c = block[end];
          if (inString) {
            if (escape) {
              escape = false;
              continue;
            }
            if (c == '\\') {
              escape = true;
              continue;
            }
            if (c == '"') {
              inString = false;
            }
            continue;
          }
          if (c == '"') {
            inString = true;
            continue;
          }
          if (c == '{') {
            ++depth;
          } else if (c == '}') {
            --depth;
            if (depth == 0) {
              break;
            }
          }
        }
        if (end >= block.size() || depth != 0) {
          break;
        }
        const auto action = block.substr(brace + 1, end - brace - 1);
        ParsedBind bind;
        bind.key = std::move(key);
        bind.action = StringUtils::trim(action);
        if (const auto ipc = ipcCommandFromAction(action); ipc.has_value()) {
          bind.ipcCommand = *ipc;
        }
        out.push_back(std::move(bind));
        i = end + 1;
      }
    }

    void collectBinds(std::string_view kdl, std::vector<ParsedBind>& out) {
      const std::string stripped = stripComments(kdl);
      std::size_t search = 0;
      while (search < stripped.size()) {
        const auto found = stripped.find("binds", search);
        if (found == std::string::npos) {
          break;
        }
        if (found > 0 && isIdent(stripped[found - 1])) {
          search = found + 5;
          continue;
        }
        if (found + 5 < stripped.size() && isIdent(stripped[found + 5])) {
          search = found + 5;
          continue;
        }
        std::size_t i = found + 5;
        while (i < stripped.size() && std::isspace(static_cast<unsigned char>(stripped[i])) != 0) {
          ++i;
        }
        if (i >= stripped.size() || stripped[i] != '{') {
          search = found + 5;
          continue;
        }
        int depth = 0;
        bool inString = false;
        bool escape = false;
        std::size_t end = i;
        for (; end < stripped.size(); ++end) {
          const char c = stripped[end];
          if (inString) {
            if (escape) {
              escape = false;
              continue;
            }
            if (c == '\\') {
              escape = true;
              continue;
            }
            if (c == '"') {
              inString = false;
            }
            continue;
          }
          if (c == '"') {
            inString = true;
            continue;
          }
          if (c == '{') {
            ++depth;
          } else if (c == '}') {
            --depth;
            if (depth == 0) {
              break;
            }
          }
        }
        if (end < stripped.size() && depth == 0) {
          collectBindsFromBlock(std::string_view(stripped).substr(i + 1, end - i - 1), out);
          search = end + 1;
        } else {
          break;
        }
      }
    }

    [[nodiscard]] std::filesystem::path resolveInclude(std::string_view raw, const std::filesystem::path& fromFile) {
      std::filesystem::path path = FileUtils::expandUserPath(std::string(raw));
      if (path.is_relative()) {
        path = fromFile.parent_path() / path;
      }
      return path.lexically_normal();
    }

    void scanRecursive(
        const std::filesystem::path& path, ConfigScan& scan, std::unordered_set<std::string>& visited, int depth
    ) {
      if (depth > 16 || path.empty()) {
        return;
      }
      std::error_code ec;
      const auto canonical = std::filesystem::weakly_canonical(path, ec);
      const std::string key = (!ec ? canonical : path).string();
      if (!visited.insert(key).second) {
        return;
      }
      const std::string text = readFile(path);
      if (text.empty() && !std::filesystem::exists(path, ec)) {
        return;
      }
      collectBinds(text, scan.binds);
      for (const auto& include : parseIncludes(text, path)) {
        if (isBindsInclude(include.string())) {
          scan.hasBindsInclude = true;
        }
        scanRecursive(include, scan, visited, depth + 1);
      }
    }

    [[nodiscard]] bool hasIncludeLine(std::string_view text, std::string_view fileName) {
      const std::string stripped = stripComments(text);
      const auto includes = parseIncludes(stripped, "dummy.kdl");
      return std::ranges::any_of(includes, [&](const std::filesystem::path& include) {
        return isBindsInclude(include.string()) || include.filename() == fileName;
      });
    }

    [[nodiscard]] bool appendInclude(const std::filesystem::path& configFile, std::string& error) {
      const std::string includeLine = std::string("include \"") + std::string(kBindsIncludeFileName) + "\"\n";
      std::error_code ec;
      if (!std::filesystem::exists(configFile, ec) || ec) {
        error = "niri config not found";
        return false;
      }
      const std::string existing = readFile(configFile);
      if (hasIncludeLine(existing, kBindsIncludeFileName)) {
        return true;
      }
      std::ofstream out(configFile, std::ios::app);
      if (!out) {
        error = "failed to update " + configFile.string();
        return false;
      }
      if (!existing.empty() && existing.back() != '\n') {
        out << '\n';
      }
      out << '\n' << includeLine;
      if (!out) {
        error = "failed to update " + configFile.string();
        return false;
      }
      return true;
    }

