    constexpr std::string_view kManagedHeader = "// Generated by Helix from Settings → Niri.\n";

    constexpr std::string_view kAutostartKdl = R"(spawn-at-startup "helix"
)";

    constexpr std::string_view kActivationKdl = R"(debug {
    honor-xdg-activation-with-invalid-serial
}
)";

    constexpr std::string_view kBackdropKdl = R"(layer-rule {
    match namespace="^helix-backdrop"
    place-within-backdrop true
}
)";

    constexpr std::string_view kLidCloseKdl = R"(switch-events {
    lid-close { spawn "helix" "msg" "session" "lid-close"; }
}
)";
    constexpr std::string_view kLegacyLidCloseSpawn =
        R"(lid-close { spawn "helix" "msg" "session" "lock-and-suspend"; })";
    constexpr std::string_view kLidCloseSpawn = R"(lid-close { spawn "helix" "msg" "session" "lid-close"; })";

    constexpr SetupItem kRequired[] = {
        {.id = "autostart", .kdl = kAutostartKdl},
        {.id = "xdg-activation", .kdl = kActivationKdl},
    };

    constexpr SetupItem kBackdrop{.id = "backdrop", .kdl = kBackdropKdl};
    constexpr SetupItem kLidClose{.id = "lid-close", .kdl = kLidCloseKdl, .optional = true};

    [[nodiscard]] bool hasKeyword(std::string_view text, std::string_view keyword) {
      std::size_t search = 0;
      while (search < text.size()) {
        const auto found = text.find(keyword, search);
        if (found == std::string_view::npos) {
          return false;
        }
        const bool leftOk = found == 0 || !isIdent(text[found - 1]);
        const auto end = found + keyword.size();
        const bool rightOk = end >= text.size() || !isIdent(text[end]);
        if (leftOk && rightOk) {
          return true;
        }
        search = found + keyword.size();
      }
      return false;
    }

    [[nodiscard]] bool hasAutostart(std::string_view text) {
      std::size_t search = 0;
      while (search < text.size()) {
        const auto found = text.find("spawn-at-startup", search);
        if (found == std::string_view::npos) {
          return false;
        }
        if ((found > 0 && isIdent(text[found - 1]))
            || (found + 16 < text.size() && isIdent(text[found + 16]))) {
          search = found + 16;
          continue;
        }
        std::size_t i = found + 16;
        if (const auto quoted = parseQuoted(text, i); quoted.has_value()) {
          if (fileNameOf(*quoted) == "helix") {
            return true;
          }
        }
        search = found + 16;
      }
      return false;
    }

    [[nodiscard]] bool itemPresent(std::string_view id, std::string_view text) {
      if (id == "autostart") {
        return hasAutostart(text);
      }
      if (id == "xdg-activation") {
        return hasKeyword(text, "honor-xdg-activation-with-invalid-serial");
      }
      if (id == "backdrop") {
        return text.find("helix-backdrop") != std::string_view::npos
            && hasKeyword(text, "place-within-backdrop");
      }
      if (id == "lid-close") {
        return hasKeyword(text, "lid-close")
            && (text.find("lock-and-suspend") != std::string_view::npos
                || text.find(R"("lid-close")") != std::string_view::npos);
      }
      return false;
    }

    [[nodiscard]] bool rewriteLidCloseSpawn(std::string& body) {
      bool changed = false;
      for (;;) {
        const auto found = body.find(kLegacyLidCloseSpawn);
        if (found == std::string::npos) {
          break;
        }
        body.replace(found, kLegacyLidCloseSpawn.size(), kLidCloseSpawn);
        changed = true;
      }
      return changed;
    }

    [[nodiscard]] bool alreadyContainsKdl(std::string_view existing, std::string_view kdl) {
      const auto strippedExisting = stripComments(existing);
      const auto strippedKdl = StringUtils::trim(stripComments(kdl));
      return strippedExisting.find(strippedKdl) != std::string::npos;
    }

