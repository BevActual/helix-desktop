  std::filesystem::path setupIncludePath() { return includePath(kSetupIncludeFileName); }

  std::span<const SetupItem> setupCatalog(bool includeBackdrop) {
    static std::vector<SetupItem> withBackdrop;
    static std::vector<SetupItem> withoutBackdrop;
    static bool initialized = false;
    if (!initialized) {
      withBackdrop.assign(std::begin(kRequired), std::end(kRequired));
      withBackdrop.push_back(kBackdrop);
      withBackdrop.push_back(kLidClose);
      withoutBackdrop.assign(std::begin(kRequired), std::end(kRequired));
      withoutBackdrop.push_back(kLidClose);
      initialized = true;
    }
    return includeBackdrop ? std::span<const SetupItem>(withBackdrop) : std::span<const SetupItem>(withoutBackdrop);
  }

  SetupScan scanSetup(bool includeBackdrop) { return scanSetupFile(configPath(), includeBackdrop); }

  SetupScan scanSetupFile(const std::filesystem::path& path, bool includeBackdrop) {
    SetupScan scan;
    scan.configPath = path;
    scan.setupIncludePath = path.parent_path() / std::string(kSetupIncludeFileName);
    std::error_code ec;
    scan.configExists = std::filesystem::exists(path, ec) && !ec;
    const std::string text = collectConfigText(path);
    const std::string includeText = readFile(scan.setupIncludePath);
    if (scan.configExists && hasInclude(readFile(path), kSetupIncludeFileName)) {
      scan.hasSetupInclude = true;
    }
    const std::string combined = text + "\n" + stripComments(includeText);
    for (const auto& item : setupCatalog(includeBackdrop)) {
      scan.items.push_back({.item = item, .present = itemPresent(item.id, combined)});
    }
    return scan;
  }

  std::vector<SetupItem> missingSetup(const SetupScan& scan) {
    std::vector<SetupItem> missing;
    for (const auto& status : scan.items) {
      if (!status.present) {
        missing.push_back(status.item);
      }
    }
    return missing;
  }

  std::string kdlBlock(std::span<const SetupItem> items) {
    std::string out;
    for (const auto& item : items) {
      out += item.kdl;
      if (!out.empty() && out.back() != '\n') {
        out.push_back('\n');
      }
      out.push_back('\n');
    }
    return out;
  }

  InstallResult installSetup(bool includeBackdrop) { return installSetupInto(configPath(), includeBackdrop); }

  InstallResult installSetupInto(const std::filesystem::path& configFile, bool includeBackdrop) {
    InstallResult result;
    if (configFile.empty()) {
      result.error = "niri config path is unknown";
      return result;
    }
    auto scan = scanSetupFile(configFile, includeBackdrop);
    if (!scan.configExists) {
      result.error = "niri config not found";
      return result;
    }

    const auto missing = missingSetup(scan);
    std::string body = readFile(scan.setupIncludePath);
    if (body.empty()) {
      body = std::string(kManagedHeader);
    } else if (body.back() != '\n') {
      body.push_back('\n');
    }
    (void)rewriteLidCloseSpawn(body);

    std::unordered_set<std::string> added;
    for (const auto& item : missing) {
      if (alreadyContainsKdl(body, item.kdl)) {
        continue;
      }
      body += item.kdl;
      if (!body.empty() && body.back() != '\n') {
        body.push_back('\n');
      }
      added.insert(std::string(item.id));
      ++result.added;
    }

    if (!writeFile(scan.setupIncludePath, body, result.error)) {
      return result;
    }
    if (!appendInclude(configFile, kSetupIncludeFileName, result.error)) {
      return result;
    }
    result.ok = true;
    return result;
  }

  bool migrateLidCloseSnippet() {
    const auto path = setupIncludePath();
    if (path.empty()) {
      return false;
    }
    std::string error;
    return migrateLidCloseSnippetIn(path, error);
  }

  bool migrateLidCloseSnippetIn(const std::filesystem::path& setupInclude, std::string& error) {
    error.clear();
    if (setupInclude.empty()) {
      error = "niri setup include path is unknown";
      return false;
    }
    std::error_code ec;
    if (!std::filesystem::exists(setupInclude, ec) || ec) {
      return false;
    }
    std::string body = readFile(setupInclude);
    if (!rewriteLidCloseSpawn(body)) {
      return false;
    }
    return writeFile(setupInclude, body, error);
  }

