#!/usr/bin/env python3
"""Generate settings_defaults_generated.rs from the C++ pristine-config catalog golden.

The golden was captured from the real C++ config defaults before that code was removed, so the Rust
bootstrap catalog stops guessing scalar defaults. List-valued rows are handled by their own
catalog code. Use `--check` in CI to verify the checked-in file is current.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GOLDEN = ROOT / "core/helix-shell-core/tests/golden/settings_catalog_defaults.json"
OUT = ROOT / "core/helix-shell-core/src/desktop/settings_defaults_generated.rs"


# Deliberate differences from the C++ config defaults (the C++ shell they described is gone).
PRODUCT_DEFAULTS = {
    # The Tauri shell registers the native Polkit agent unless told otherwise (README, example.toml).
    "shell.polkit_agent": "DefaultValue::Bool(true)",
}


def render() -> str:
    rows = json.loads(GOLDEN.read_text())
    lines = []
    for row in sorted(rows, key=lambda r: r["id"]):
        rid, value = row["id"], row.get("value")
        if rid.startswith(("bar:", "idle:")) or isinstance(value, (list, dict)) or value is None:
            continue
        if isinstance(value, bool):
            lit = f"DefaultValue::Bool({'true' if value else 'false'})"
        elif isinstance(value, (int, float)):
            # C++ stores float32; keep the shortest decimal that round-trips at that precision.
            number = float(f"{float(value):.7g}")
            lit = f"DefaultValue::Number({number!r})"
        elif isinstance(value, str):
            lit = f"DefaultValue::Str({json.dumps(value)})"
        else:
            continue
        lit = PRODUCT_DEFAULTS.get(rid, lit)
        lines.append(f'        "{rid}" => Some({lit}),')
    body = "\n".join(lines)
    return f"""//! @generated by tools/gen-rust-settings-defaults.py from tests/golden/settings_catalog_defaults.json.
//! Scalar defaults of a pristine C++ config; do not edit by hand.

use super::settings::DefaultValue;

pub fn cpp_default(id: &str) -> Option<DefaultValue> {{
    match id {{
{body}
        _ => None,
    }}
}}
"""


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("settings_defaults_generated.rs is stale; run tools/gen-rust-settings-defaults.py", file=sys.stderr)
            sys.exit(1)
    else:
        OUT.write_text(text)
